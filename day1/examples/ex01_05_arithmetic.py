# 간단한 사칙연산 — 계산기처럼 사용하기

# 더하기
print("3 + 5 =", 3 + 5)         # 8

# 빼기
print("10 - 3 =", 10 - 3)       # 7

# 곱하기
print("4 × 5 =", 4 * 5)         # 20

# 나누기 (항상 실수로 결과)
print("10 ÷ 3 =", 10 / 3)       # 3.3333...

# 몫 (소수점 버림)
print("10 ÷ 3의 몫 =", 10 // 3) # 3

# 나머지
print("10 ÷ 3의 나머지 =", 10 % 3)  # 1

# 거듭제곱 (제곱)
print("2의 10승 =", 2 ** 10)    # 1024
print("3의 4승 =", 3 ** 4)      # 81

# 복합 계산
print()
print("복합 계산 예시:")
print("(10 + 5) × 2 =", (10 + 5) * 2)     # 30
print("100 - 3 × 20 =", 100 - 3 * 20)     # 40 (곱셈이 먼저!)
print("(100 - 3) × 20 =", (100 - 3) * 20) # 1940
