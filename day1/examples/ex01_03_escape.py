# 줄바꿈과 특수 문자

# \n — 줄바꿈 (new line)
print("첫 번째 줄\n두 번째 줄\n세 번째 줄")

print()  # 빈 줄

# \t — 탭 (tab, 일정 간격 띄우기)
print("이름\t나이\t직업")
print("철수\t25\t학생")
print("영희\t30\t개발자")
print("민수\t28\t디자이너")

print()

# \\ — 백슬래시 자체를 출력
print("파일 경로: C:\\Users\\Documents")

# \" 또는 \' — 따옴표 출력
print("그는 \"파이썬 최고!\"라고 말했다")
print('It\'s a beautiful day')
